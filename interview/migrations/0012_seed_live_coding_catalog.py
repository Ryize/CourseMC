def seed_live_coding_catalog(apps, schema_editor):
    Task = apps.get_model('interview', 'LiveCodingTask')
    Category = apps.get_model('interview', 'InterviewQuestionCategory')
    framework_categories = {
        title.casefold(): category
        for title, category in Category.objects.filter(
            title__in=('Django', 'FastAPI'),
        ).in_bulk(field_name='title').items()
    }

    for title, description, category, level, complexity, duration in TASKS:
        task, _ = Task.objects.update_or_create(
            title=title,
            defaults={
                'description': description,
                'category': category,
                'level': level,
                'complexity': complexity,
                'duration_minutes': duration,
                'is_active': True,
            },
        )
        if category in ('django', 'fastapi'):
            framework = framework_categories.get(category)
            if framework is not None:
                task.frameworks.set((framework,))
        else:
            task.frameworks.clear()


