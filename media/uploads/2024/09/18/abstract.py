# Абстрагирование - Процесс перехода на более высокий уровень абстракции.

# Абстрактный класс - класс, у которого есть хотя бы один абстрактный метод.
# Абстрактный метод - метод, который был создан в классе, но не имеет
# реализации.

# Первое назначение абстракции - класс шаблон, который помогает разработчикам
# поддерживать одинаковую структуру классов.
from abc import ABC, abstractmethod


class AbstractCar(ABC):
    @abstractmethod
    def start(self):
        pass

    @abstractmethod
    def ride(self):
        pass


class BMW(AbstractCar):
    def start(self):
        print('Запускаю машину')

    def ride(self):
        print('Еду')


class Audi(AbstractCar):
    def start(self):
        print('Включаю машину')

    def ride(self):
        print('Начинаю езду')


class Volvo(AbstractCar):
    def start(self):
        print('Завожу машину')

    def ride(self):
        print('Безопасное вождение')


bmw = BMW()
audi = Audi()
volvo = Volvo()

bmw.start()
audi.ride()
volvo.start()


