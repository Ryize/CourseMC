# реализации.


# Уровни абстракции - уровень детализации (какого-либо процесса/объекта).
# 1) Физический
# 2) Процессорные языки (языки ассемблера)
# 3) Низкоуровневые языки (C, Fortran, Lisp, Cobol)
# 4) Высокоуровневые языки (Java, Python, C++, C#, JS, Go)
